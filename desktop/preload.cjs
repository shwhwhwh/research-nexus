const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('workspace', {
  showTool: (tool, url) => ipcRenderer.invoke('show-tool', { tool, url }),
  hideTool: () => ipcRenderer.invoke('hide-tool'),
  getState: () => ipcRenderer.invoke('workspace-state'),
  getAppearance: () => ipcRenderer.invoke('appearance-get'),
  setAppearance: source => ipcRenderer.invoke('appearance-set',source),
  onAppearance: callback => ipcRenderer.on('appearance-state',(_event,value)=>callback(value)),
  windowAction: action => ipcRenderer.invoke('window-action',action),
  navigate: (action) => ipcRenderer.invoke('navigate-tool', action),
  toggleFullscreen: () => ipcRenderer.invoke('toggle-fullscreen'),
  onFullscreenState: (callback) => ipcRenderer.on('fullscreen-state', (_event, value) => callback(value)),
  launchZotero: () => ipcRenderer.invoke('launch-zotero'),
  launchOpenResearch: () => ipcRenderer.invoke('launch-openresearch'),
  showNativeTool: (tool, itemKey) => ipcRenderer.invoke('show-native-tool', {tool,itemKey}),
  releaseNativeTool: () => ipcRenderer.invoke('release-native-tool'),
  zoteroAccountSettings: () => ipcRenderer.invoke('zotero-account-settings'),
  onNativeToolState: (callback) => ipcRenderer.on('native-tool-state', (_event,data) => callback(data)),
  choosePdfFolder: () => ipcRenderer.invoke('choose-pdf-folder'),
  chooseToolExecutable: () => ipcRenderer.invoke('choose-tool-executable'),
  chooseSystemTemplate: () => ipcRenderer.invoke('choose-system-template'),
  saveBlueprint: jobId => ipcRenderer.invoke('save-blueprint',jobId),
  saveSystemTemplate: manifest => ipcRenderer.invoke('save-system-template',manifest),
  openSetupLink: key => ipcRenderer.invoke('open-setup-link',key),
  openDesignerNode: id => ipcRenderer.invoke('open-designer-node',id),
  onOpenDesigner: callback => ipcRenderer.on('open-designer',()=>callback()),
  onOpenSystems: callback => ipcRenderer.on('open-systems',()=>callback()),
  onToolState: (callback) => ipcRenderer.on('tool-state', (_event, data) => callback(data)),
});
